"""Create the named 16 kHz PCM voice bank, preserving source WAVs unchanged."""
import argparse, array, hashlib, json, sys, wave
from pathlib import Path
from import_samples import read_wav

ROOT = Path(__file__).resolve().parents[1]
RATE = 16000
CLIPS = [
    ('EAT_TV', 'eat 1.wav', 'Burger from the stack while watching TV'),
    ('EAT_FEED', 'eat 2.wav', 'User feeds him'),
    ('NEWS', 'fake news.wav', 'Occasional complaint while watching news'),
    ('HUNGRY', 'i want food.wav', 'Food at or below 25'),
    ('TIRED', 'i want sleep.wav', 'Energy at or below 20, or nighttime'),
    ('REFUSE', 'id rather not.wav', 'Refused care action'),
    ('PERFECT', 'perfect.wav', 'After deposit and after Poo finishes'),
    ('POO', 'poo.wav', 'During the poo crouch'),
    ('SNORE', 'snore.wav', 'While tucked into bed'),
    ('PRAISE_1', 'thank you thank you.wav', 'Praise alternate one'),
    ('PRAISE_2', 'thank you very much.wav', 'Praise alternate two'),
    ('CLEAN', 'very clean.wav', 'Accepted CLEAN action'),
]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('folder', nargs='?', type=Path, default=ROOT/'samples/voice-originals')
    args = parser.parse_args()
    data, manifest = [], []
    converted = ROOT/'samples/voice-16k'
    converted.mkdir(parents=True, exist_ok=True)
    for ident, filename, trigger in CLIPS:
        source = args.folder/filename
        samples = read_wav(source, output_rate=RATE)
        pcm = array.array('h', samples)
        if sys.byteorder != 'little': pcm.byteswap()
        with wave.open(str(converted/filename), 'wb') as wav:
            wav.setparams((1, 2, RATE, 0, 'NONE', 'not compressed'))
            wav.writeframes(pcm.tobytes())
        data.append(samples)
        manifest.append(dict(id=ident, source_file=filename, trigger=trigger,
            frames=len(samples), seconds=len(samples)/RATE,
            source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
            pcm_sha256=hashlib.sha256(pcm.tobytes()).hexdigest(),
            source_url=None, rights='User-supplied recordings; specific source links pending'))
    size = sum(len(x)*2 for x in data)
    # Keep PCM near the measured 404 KiB allocation; final build enforces APP_SLOT.
    if size > 414*1024: raise ValueError(f'Voice payload too large: {size} bytes')
    lines = ['/* Generated by tools/import_voice_samples.py. */',
        '/* Recording rights are separate from the code licence; see voice_bank.json. */',
        '#pragma once', '#include <stdint.h>', '#include "pet_voice.h"',
        '#define PET_VOICE_RATE 16000u',
        'typedef struct { const int16_t *data; uint32_t length; } pet_voice_clip_t;']
    for (ident, _, _), samples in zip(CLIPS, data):
        lines.append(f'static const int16_t voice_{ident}[] = {{')
        lines.extend(','.join(str(v) for v in samples[i:i+24])+',' for i in range(0,len(samples),24))
        lines.append('};')
    lines.append('static const pet_voice_clip_t pet_voice_clips[PV_COUNT] = {')
    lines.extend('{voice_%s,%du},'%(clip[0],len(samples)) for clip,samples in zip(CLIPS,data))
    lines.append('};')
    out = ROOT/'firmware/src/dsp/voice_bank.h'
    out.write_text('\n'.join(lines)+'\n')
    out.with_suffix('.json').write_text(json.dumps(dict(sample_rate=RATE,bit_depth=16,
        channels=1,pcm_bytes=size,seconds=size/(RATE*2),samples=manifest),indent=2)+'\n')
    print(f'{len(data)} clips, {size} PCM bytes, {size/(RATE*2):.3f} seconds')

if __name__ == '__main__': main()
